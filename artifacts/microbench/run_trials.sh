#!/usr/bin/env bash
set -euo pipefail
ROOT="$(cd "$(dirname "$0")" && pwd)"
CXX="${CXX:-clang++}"
FLAGS="-O2 -std=c++17 -march=native"
BIN="$ROOT/enet_recv_queue_bench"
OUT="$ROOT/results.jsonl"
mkdir -p "$(dirname "$OUT")"
$CXX $FLAGS "$ROOT/enet_recv_queue_bench.cpp" -o "$BIN"
: >"$OUT"
echo "# interleaved order: baseline1, opt1, opt2, baseline2, baseline3, opt3" >>"$OUT"
echo "# pinned_source_sha=5c3065c261fb3ba82032fee6803f247198fec221" >>"$OUT"
"$BIN" baseline 1 | tee -a "$OUT"
"$BIN" optimized 1 | tee -a "$OUT"
"$BIN" optimized 2 | tee -a "$OUT"
"$BIN" baseline 2 | tee -a "$OUT"
"$BIN" baseline 3 | tee -a "$OUT"
"$BIN" optimized 3 | tee -a "$OUT"
echo "Wrote $OUT"
